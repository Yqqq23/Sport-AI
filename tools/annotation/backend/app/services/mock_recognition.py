"""FAKE jersey predictions for UI development. NOT a recognition model.

READ THIS BEFORE TRUSTING ANYTHING THIS MODULE PRODUCES.

Nothing here looks at the image. The player boxes are drawn from an arithmetic
lane layout keyed on ``track_id``, the jersey boxes are a fixed fraction of those
boxes, the numbers come from a hardcoded seven-entry lookup table, and the
confidences are ``random.random()`` scaled into a plausible-looking range. The
output is therefore indistinguishable from a real detection by shape alone -
same schema, same value ranges, same shape of confidence distribution - which is
exactly what makes it dangerous.

It is kept rather than deleted because it is the only way to exercise the review
and export flow without a GPU or model weights. Every row it produces is stamped
``source = PREDICTION_SOURCE_MOCK`` in the database, the API echoes that on every
review item, and the UI shows a persistent banner. If you are seeing mock data,
you should be told three times before you draw a single box.

TO REPLACE THIS WITH REAL RECOGNITION - no code change is needed here:

  Interface        ``run(video_id: int, db: Session) -> list[JerseyPrediction]``
  Real impl        ``app/services/real_recognition.py::RealJerseyRecognizer``
                   already implements it and is already wired up.
  Endpoint         POST /videos/{video_id}/run-jersey-recognition-async
                   (job runner: routes._run_jersey_recognition_job)
                   as opposed to the mock endpoint
                   POST /videos/{video_id}/run-mock-jersey-recognition-async
                   (job runner: routes._run_mock_jersey_recognition_job)
  Config           REAL_RECOGNITION_ENABLED, SPORT_CV_ROOT,
                   PLAYER_DETECTOR_WEIGHTS, JERSEY_OCR_WEIGHTS in backend/.env
                   (see app/core/config.py)
  Detector-only    POST /videos/{video_id}/run-yolo-preannotation-async
                   (app/services/yolo_preannotation.py) - boxes without numbers.

  A basketball-v2 5-class detector would slot in at the same place: give
  YoloPreannotator the trained best.pt instead of yolov8n.pt and emit one
  prediction per detected box with its class_id. That is the intended path once
  weights exist, and it is deliberately NOT implemented yet.
"""

from __future__ import annotations

import json
import logging
import random
from pathlib import Path

import cv2

from app.models.dataset import (
    PREDICTION_SOURCE_MOCK,
    PREDICTION_SOURCE_REAL,
    PREDICTION_SOURCE_YOLO,
    JerseyPrediction,
    VideoAsset,
    VideoFrame,
)

LOGGER = logging.getLogger(__name__)

NUMBERS = ["0", "7", "11", "23", "28"]

#: Shown in the API response and in the UI banner. Deliberately blunt.
MOCK_PREDICTION_WARNING = (
    "MOCK DATA - these boxes, numbers and confidences are generated by "
    "app/services/mock_recognition.py and were NEVER computed from the image. "
    "They are for exercising the annotation UI only. Do not read them as "
    "recognition results, and do not treat corrections to them as measuring "
    "anything. Run 'jersey recognition' or 'YOLO pre-annotation' for real boxes."
)

#: Sources that came from something that actually looked at the pixels.
REAL_PREDICTION_SOURCES = frozenset({PREDICTION_SOURCE_YOLO, PREDICTION_SOURCE_REAL})


def is_mock_prediction(prediction: JerseyPrediction | None) -> bool:
    """True when a prediction row is known-fake.

    Rows written before the ``source`` column existed are 'unknown' and are NOT
    reported as mock - claiming to know their provenance would be a guess. They
    are reported as unverified instead.
    """
    if prediction is None:
        return False
    return str(getattr(prediction, "source", "")) == PREDICTION_SOURCE_MOCK


def _clamp_bbox(x1: int, y1: int, x2: int, y2: int, width: int, height: int) -> list[int]:
    x1 = max(0, min(width - 1, x1))
    y1 = max(0, min(height - 1, y1))
    x2 = max(x1 + 1, min(width, x2))
    y2 = max(y1 + 1, min(height, y2))
    return [x1, y1, x2, y2]


def _player_bbox(track_id: int, frame_id: int, width: int, height: int) -> list[int]:
    lane_width = max(60, width // 10)
    lane_height = max(140, height // 4)
    base_x = int((track_id * width) / 8)
    drift = int(18 * ((frame_id // 5) % 6)) - 36
    x1 = base_x + drift
    y1 = int(height * 0.38) + (track_id % 3) * 20 + int(10 * ((frame_id // 9) % 3))
    return _clamp_bbox(x1, y1, x1 + lane_width, y1 + lane_height, width, height)


def _jersey_bbox(player_bbox: list[int]) -> list[int]:
    x1, y1, x2, y2 = player_bbox
    w = x2 - x1
    h = y2 - y1
    jx1 = x1 + int(w * 0.28)
    jx2 = x2 - int(w * 0.22)
    jy1 = y1 + int(h * 0.18)
    jy2 = y1 + int(h * 0.48)
    return [jx1, jy1, jx2, jy2]


def _predicted_number(track_id: int, frame_index: int) -> str:
    canonical = {1: "23", 2: "11", 3: "7", 4: "0", 5: "28", 6: "23", 7: "11"}
    if track_id == 1 and frame_index == 2:
        return "28"
    return canonical.get(track_id, NUMBERS[(track_id - 1) % len(NUMBERS)])


def generate_mock_predictions(video: VideoAsset, frames: list[VideoFrame]) -> list[JerseyPrediction]:
    """Invent predictions. See the module docstring - none of this is real."""
    LOGGER.warning(
        "GENERATING MOCK PREDICTIONS for video_id=%s. %s", video.id, MOCK_PREDICTION_WARNING
    )
    rng = random.Random(video.id)
    capture = cv2.VideoCapture(video.path)
    width = int(capture.get(cv2.CAP_PROP_FRAME_WIDTH) or 1920)
    height = int(capture.get(cv2.CAP_PROP_FRAME_HEIGHT) or 1080)
    capture.release()

    predictions: list[JerseyPrediction] = []
    track_pool = [1, 2, 3, 4, 5, 6, 7]
    for frame_index, frame in enumerate(frames):
        active_count = 5 + (frame_index % 3)
        active_tracks = track_pool[:active_count]
        for track_id in active_tracks:
            player_bbox = _player_bbox(track_id, frame.frame_id, width, height)
            jersey_bbox = _jersey_bbox(player_bbox)
            base_conf = 0.55 + 0.35 * rng.random()
            if (frame_index + track_id) % 11 == 0:
                base_conf = 0.31 + 0.08 * rng.random()
            predictions.append(
                JerseyPrediction(
                    video_id=video.id,
                    frame_row_id=frame.id,
                    frame_id=frame.frame_id,
                    track_id=track_id,
                    player_bbox=json.dumps(player_bbox),
                    jersey_bbox=json.dumps(jersey_bbox),
                    predicted_number=_predicted_number(track_id, frame_index),
                    confidence=round(base_conf, 3),
                    source=PREDICTION_SOURCE_MOCK,
                )
            )
    LOGGER.warning(
        "Produced %s MOCK predictions for video_id=%s (source=%s)",
        len(predictions),
        video.id,
        PREDICTION_SOURCE_MOCK,
    )
    return predictions
